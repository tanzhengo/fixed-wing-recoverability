#!/usr/bin/env python3
"""Generate the isolated building-geometry extension of the frozen planner.

The released forest/learning implementation remains unchanged. All inserted
lines are declared below; --check verifies both the frozen input and generated
header, making the difference reproducible without duplicating hand edits.
"""
from pathlib import Path
import argparse
import hashlib
import json

PACKAGE = Path(__file__).resolve().parents[1]
BASE = PACKAGE / 'src/motion_primitives.h'
DESTINATION = PACKAGE / 'src/urban_motion_primitives.h'
BASE_SHA256 = 'a08773a2f3c79a9f3f481590b8d197ff933f01b1670ccf0e5de31293b588fc73'


def replace_once(text, anchor, replacement):
    if text.count(anchor) != 1:
        raise RuntimeError('Expected one insertion anchor: ' + repr(anchor))
    return text.replace(anchor, replacement, 1)


def generate():
    data = BASE.read_bytes()
    if hashlib.sha256(data).hexdigest() != BASE_SHA256:
        raise RuntimeError('The frozen baseline header does not match the declared version')
    text = data.decode('utf-8')
    text = replace_once(text, '#include "learned_recovery.h"',
                        '#include "learned_recovery.h"\n#include "urban_box_geometry.h"')
    text = replace_once(text, 'class MotionPrimitives {\npublic:\n', '''class MotionPrimitives {
public:
    using urban_box_t = urban_geometry::Box;

    // Install the physical building components before starting an episode.
    // Invalid maps fail atomically; a previous map is not partially replaced.
    void set_urban_boxes(const std::vector<urban_box_t>& boxes) {
        for (const auto& box : boxes)
            if (!urban_geometry::valid(box))
                throw std::invalid_argument("Invalid urban building dimensions");
        urban_boxes_ = boxes;
    }
    const std::vector<urban_box_t>& urban_boxes() const { return urban_boxes_; }

''')
    text = replace_once(text, '        float distance = 30.0f;\n', '''        float distance = 30.0f;
        for (const auto& box : urban_boxes_)
            distance = std::min(distance, static_cast<float>(
                urban_geometry::signed_distance(box, x, y, z)));
''')
    anchor = '''        for (const auto& obs : static_obs_vec) {
            if (inside_cylinder(x, y, z, obs.pos[0], obs.pos[1], obs.z, obs.r, obs.height))'''
    text = replace_once(text, anchor, '''        for (const auto& box : urban_boxes_)
            if (urban_geometry::signed_distance(box, x, y, z) <= 0.0) return true;
''' + anchor)
    text = replace_once(text, '    std::vector<obs_t> static_obs_vec;\n',
                        '    std::vector<obs_t> static_obs_vec;\n    std::vector<urban_box_t> urban_boxes_;\n')
    banner = ('// Generated by scripts/generate_urban_planner.py; do not hand edit.\n'
              '// Frozen source SHA-256: ' + BASE_SHA256 + '\n'
              '// Only building storage, map installation, collision and SDF are added.\n'
              '// Include this header BEFORE evaluation_plant.h or frozen benchmark helpers.\n')
    return (banner + text).encode('utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_bytes() != generated:
            raise RuntimeError('Generated urban header is missing or stale')
    else:
        DESTINATION.write_bytes(generated)
    print(json.dumps({'frozen_source_sha256': BASE_SHA256,
                      'generated_header_sha256': hashlib.sha256(generated).hexdigest(),
                      'generator_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                      'box_geometry_sha256': hashlib.sha256((PACKAGE / 'src/urban_box_geometry.h').read_bytes()).hexdigest(),
                      'check_passed': True}, indent=2))
